"""
evaluation/eval_cloud_compare.py
─────────────────────────────────────────────────────────────────
Evaluates Cloud LLM agent results.
  - Generated by OpenAI GPT-4o (or whatever model)
  - Judged by Claude Sonnet 4.6

Loads:
  LLM_as_a_Judge/claudeAI/cloud.json  ← realism scores from Claude judge

Produces:
  eval_cloud_fidelity.png     ← cosine/sequence/BLEU/BERT vs ground truth
  eval_cloud_realism.png      ← realism scores by FI (LLM-as-a-Judge)

Run:
  cd evaluation
  python eval_cloud_compare.py
─────────────────────────────────────────────────────────────────
"""

import json
import os
import sys
import numpy as np
from collections import defaultdict
import matplotlib.pyplot as plt

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from fidelity import score_all
from fi_manager import FIScorer, FI_LABELS

# ─── Config ───────────────────────────────────────────────────────────────────

CLOUD_REALISM_FILE   = "LLM_as_a_Judge/claudeAI/cloud.json"
CLOUD_RESPONSE_FILE  = "/mnt/data-partition/honeypot/evaluation/cloud_agent_dataset/cloud_chatGPT.json"
ONDEVICE_FILE        = "eval_ondevice_results.json"     # used to get ground_truth by cmd
OUTPUT_DIR         = "/mnt/data-partition/honeypot/evaluation/experiment_results"
MAX_ENTRIES        = 481
START_INDEX        = 0

GRAPH_TITLE_TAG    = "Generated by ChatGPT-5| Judged by Claude Sonnet 4.6"

scorer     = FIScorer()
FI_COLORS  = ["#2ecc71", "#3498db", "#f39c12", "#e67e22", "#e74c3c"]
os.makedirs(OUTPUT_DIR, exist_ok=True)

# ─── Load ─────────────────────────────────────────────────────────────────────

def load_json(path: str) -> list:
    if not os.path.exists(path):
        print(f"[!] Not found: {path}")
        return []
    with open(path) as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            print(f"[!] Failed to parse: {path}")
            return []
    if MAX_ENTRIES is not None:
        data = data[START_INDEX:START_INDEX + MAX_ENTRIES]
    print(f"[INFO] Loaded {len(data)} entries from {path}")
    return data

# ─── Helpers ──────────────────────────────────────────────────────────────────

def _fi_labels_short():
    return [f"FI {fi}\n{FI_LABELS[fi][:10]}.." for fi in range(5)]

def group_by_fi(results: list) -> dict:
    groups = defaultdict(list)
    for r in results:
        cmd = r.get("cmd") or r.get("command", "")
        fi, _ = scorer.score(cmd)
        r["fi"] = fi
        groups[fi].append(r)
    return groups

def group_realism_by_fi(data: list) -> dict:
    groups = defaultdict(list)
    for d in data:
        score = d.get("realism_score")
        if score is None:
            continue
        cmd = d.get("command", d.get("cmd", ""))
        fi, _ = scorer.score(cmd)
        groups[fi].append(score)
    return groups

# ─── Print Summaries ──────────────────────────────────────────────────────────

def print_fidelity_summary(results: list):
    valid = [r for r in results if not r.get("skipped")]
    total = len(valid)
    if not total:
        print("[!] No valid results to summarize")
        return

    def avg(key):
        vals = [r[key] for r in valid if r.get(key) is not None]
        return sum(vals) / len(vals) if vals else 0

    exact = sum(1 for r in valid if r.get("exact_match") == 1)

    print(f"\n{'═'*55}")
    print(f"  CLOUD LLM — FIDELITY SUMMARY")
    print(f"  {GRAPH_TITLE_TAG}")
    print(f"{'═'*55}")
    print(f"  Total commands   : {total}")
    print(f"  Avg cosine sim   : {avg('cosine_score'):.4f}   (semantic)")
    print(f"  Avg sequence sim : {avg('sequence_score'):.4f}   (syntax/structure)")
    print(f"  Avg BLEU         : {avg('bleu_score'):.4f}   (n-gram overlap)")
    print(f"  Avg BERTScore F1 : {avg('bert_f1'):.4f}   (deep semantic)")
    print(f"  Exact matches    : {exact} / {total}  ({exact/total*100:.1f}%)")
    print("═" * 55 + "\n")

def print_fidelity_by_fi(groups: dict):
    print(f"\n{'═'*70}")
    print(f"  CLOUD LLM — FIDELITY BY FI GROUP")
    print(f"{'═'*70}")
    print(f"  {'FI':<5} {'LABEL':<30} {'CMDS':>5}  {'COSINE':>8}  {'SEQ':>8}  {'BLEU':>8}  {'BERT':>8}")
    print("─" * 70)
    for fi in range(5):
        group = groups.get(fi, [])
        if not group:
            print(f"  {fi:<5} {FI_LABELS[fi]:<30} {'0':>5}  {'N/A':>8}")
            continue
        def avg(k): return sum(r.get(k, 0) for r in group) / len(group)
        print(f"  {fi:<5} {FI_LABELS[fi]:<30} {len(group):>5}"
              f" {avg('cosine_score'):>8.4f}  {avg('sequence_score'):>8.4f}"
              f"  {avg('bleu_score'):>8.4f}  {avg('bert_f1'):>8.4f}")
    print("═" * 70 + "\n")

def print_realism_summary(realism_data: list):
    scores = [d["realism_score"] for d in realism_data if "realism_score" in d]
    if not scores:
        print("[!] No realism scores found")
        return
    avg = sum(scores) / len(scores)
    print(f"\n{'═'*55}")
    print(f"  CLOUD LLM — REALISM SUMMARY (LLM-as-a-Judge)")
    print(f"  {GRAPH_TITLE_TAG}")
    print(f"{'═'*55}")
    print(f"  Total judged     : {len(scores)}")
    print(f"  Avg realism score: {avg:.3f} / 5.0")
    print(f"  Min / Max        : {min(scores):.1f} / {max(scores):.1f}")
    print("═" * 55 + "\n")

def print_realism_by_fi(realism_data: list):
    groups = group_realism_by_fi(realism_data)
    print(f"\n{'═'*50}")
    print(f"  CLOUD LLM — REALISM BY FI GROUP")
    print(f"{'═'*50}")
    print(f"  {'FI':<5} {'LABEL':<30} {'CMDS':>5} {'AVG':>8}")
    print("─" * 50)
    for fi in range(5):
        scores = groups.get(fi, [])
        avg    = sum(scores) / len(scores) if scores else 0
        print(f"  {fi:<5} {FI_LABELS[fi]:<30} {len(scores):>5} {avg:>8.3f}")
    print("═" * 50 + "\n")

# ─── Plot: Fidelity (vs ground truth) ────────────────────────────────────────

def plot_cloud_fidelity(scored: list, groups: dict):
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    fig.suptitle(f"Cloud LLM — Fidelity vs Ground Truth\n{GRAPH_TITLE_TAG}", fontsize=12)

    # ── Left: overall score distribution ──────────────────────────────────────
    ax = axes[0]
    metrics = {
        "Cosine":   "cosine_score",
        "Sequence": "sequence_score",
        "BLEU":     "bleu_score",
        "BERT F1":  "bert_f1",
    }
    colors = ["#3498db", "#2ecc71", "#e67e22", "#9b59b6"]
    avgs   = []
    for (label, key), color in zip(metrics.items(), colors):
        vals = [r[key] for r in scored if r.get(key) is not None]
        avg  = sum(vals) / len(vals) if vals else 0
        avgs.append(avg)
        ax.bar(label, avg, color=color, alpha=0.85)
        ax.text(list(metrics.keys()).index(label), avg + 0.01,
                f"{avg:.3f}", ha="center", va="bottom", fontsize=9)
    ax.set_ylim(0, 1.0)
    ax.set_ylabel("Score (0–1)")
    ax.set_title("Overall Fidelity Scores")
    ax.grid(True, axis="y", alpha=0.3)

    # ── Right: grouped bar per FI ──────────────────────────────────────────────
    ax = axes[1]
    x         = np.arange(5)
    bar_width = 0.18
    for i, (label, key) in enumerate(metrics.items()):
        values = [
            sum(r.get(key, 0) for r in groups.get(fi, [])) / len(groups.get(fi, [1]))
            if groups.get(fi) else 0
            for fi in range(5)
        ]
        offset = (i - len(metrics)/2 + 0.5) * bar_width
        ax.bar(x + offset, values, bar_width, label=label,
               color=colors[i], alpha=0.85)
    ax.set_xticks(x)
    ax.set_xticklabels(_fi_labels_short())
    ax.set_ylim(0, 1.0)
    ax.set_ylabel("Score (0–1)")
    ax.set_title("Fidelity by FI Group\n(cosine / sequence / BLEU / BERT)")
    ax.legend(fontsize=8, loc="upper right")
    ax.grid(True, axis="y", alpha=0.3)

    plt.tight_layout()
    out = os.path.join(OUTPUT_DIR, "eval_cloud_fidelity.png")
    plt.savefig(out, dpi=150)
    print(f"[✓] Saved → {out}")
    plt.close()

# ─── Plot: Realism (LLM-as-a-Judge) ──────────────────────────────────────────

def plot_cloud_realism(realism_data: list):
    fi_groups = group_realism_by_fi(realism_data)

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    fig.suptitle(f"Cloud LLM — Realism (LLM-as-a-Judge)\n{GRAPH_TITLE_TAG}", fontsize=12)

    # ── Left: realism score distribution (histogram) ──────────────────────────
    ax = axes[0]
    scores = [d["realism_score"] for d in realism_data if "realism_score" in d]
    ax.hist(scores, bins=[0.5, 1.5, 2.5, 3.5, 4.5, 5.5],
            color="#3498db", alpha=0.8, edgecolor="white")
    ax.axvline(x=sum(scores)/len(scores), color="red", linestyle="--",
               linewidth=1.5, label=f"Avg = {sum(scores)/len(scores):.2f}")
    ax.set_xlabel("Realism Score (1–5)")
    ax.set_ylabel("Count")
    ax.set_title("Realism Score Distribution")
    ax.legend()
    ax.grid(True, axis="y", alpha=0.3)

    # ── Right: avg realism per FI group ───────────────────────────────────────
    ax = axes[1]
    fi_avgs   = []
    fi_counts = []
    for fi in range(5):
        s = fi_groups.get(fi, [])
        fi_counts.append(len(s))
        fi_avgs.append(sum(s) / len(s) if s else 0)

    bars = ax.bar(_fi_labels_short(), fi_avgs, color=FI_COLORS, alpha=0.85)
    for bar, count, val in zip(bars, fi_counts, fi_avgs):
        ax.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 0.05,
                f"{val:.2f}\n(n={count})", ha="center", va="bottom", fontsize=8)
    ax.set_ylim(0, 5.5)
    ax.set_ylabel("Avg Realism Score (1–5)")
    ax.set_title("Realism by FI Group")
    ax.grid(True, axis="y", alpha=0.3)

    plt.tight_layout()
    out = os.path.join(OUTPUT_DIR, "eval_cloud_realism.png")
    plt.savefig(out, dpi=150)
    print(f"[✓] Saved → {out}")
    plt.close()

# ─── Main ─────────────────────────────────────────────────────────────────────

def run():
    # ── Load actual cloud responses (473 entries — full dataset) ─────────────
    cloud_responses_raw = load_json(CLOUD_RESPONSE_FILE)
    if not cloud_responses_raw:
        print("[!] No cloud responses found, exiting.")
        return

    # ── Load ground truth: ondevice first, cowrie as fallback ────────────────
    gt_lookup = {}
    for r in load_json(ONDEVICE_FILE):
        cmd = r.get("cmd", "")
        if cmd:
            gt_lookup[cmd] = r.get("ground_truth", "")
    for r in load_json("eval_cowrie_results.json"):
        cmd = r.get("cmd", "")
        if cmd and cmd not in gt_lookup:
            gt_lookup[cmd] = r.get("ground_truth", r.get("cowrie_output", ""))

    # ── Build scoreable list from ALL 473 cloud responses ────────────────────
    scored_input = []
    missing_gt   = 0
    for r in cloud_responses_raw:
        cmd  = r.get("cmd", "")
        gt   = gt_lookup.get(cmd, "")
        resp = r.get("response", "")
        if not gt:
            missing_gt += 1
        scored_input.append({
            "cmd":          cmd,
            "ground_truth": gt,
            "cloud_output": resp,
        })

    print(f"[INFO] Total cloud responses : {len(scored_input)}")
    print(f"[INFO] GT matched            : {len(scored_input) - missing_gt}/{len(scored_input)}")
    print(f"[INFO] GT missing            : {missing_gt}")

    # ── Score fidelity against ground truth ───────────────────────────────────
    scored = score_all(scored_input, method="all", output_key="cloud_output")
    groups = group_by_fi(scored)

    # ── Print fidelity summaries ──────────────────────────────────────────────
    print_fidelity_summary(scored)
    print_fidelity_by_fi(groups)

    # ── Plot fidelity ─────────────────────────────────────────────────────────
    plot_cloud_fidelity(scored, groups)

    # ── Realism (LLM-as-a-Judge) — separate, only 228 entries, that's fine ───
    realism_data = load_json(CLOUD_REALISM_FILE)
    if realism_data:
        print_realism_summary(realism_data)
        print_realism_by_fi(realism_data)
        plot_cloud_realism(realism_data)
    else:
        print("[!] No realism data found, skipping realism plots.")

    print("\n[✓] Cloud eval complete.")

if __name__ == "__main__":
    run()