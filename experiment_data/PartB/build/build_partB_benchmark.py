# Interactive / destructive bases — skip entirely
SKIP_BASES = {
    "vim", "vi", "nano", "emacs", "less", "more", "top", "htop",
    "passwd", "su", "sudo", "ssh", "telnet", "ftp", "nc", "ncat",
    "python", "python3", "perl", "ruby", "php", "node", "lua",
    "bash", "sh", "zsh", "mysql", "psql", "mongo",
    "reboot", "shutdown", "halt", "poweroff", "init",
    "dd", "mkfs", "fdisk", "parted", "ftpget", "tftp",
    "scp", "sftp",
}

SKIP_PATTERNS = [
    r'rm\s+.*-rf?\s+/',          # rm -rf /
    r'>\s*/etc/(passwd|shadow)', # overwrite system files
    r'chmod\s+(777|000)\s+/',    # chmod on root
    r'kill.*-9',
    r'pkill|killall',
    r'curl.*\|\s*(bash|sh)',     # pipe to shell — unsafe
    r'wget.*\|\s*(bash|sh)',
    r'wget.*&&\s*(bash|sh)',
    r'\|\s*sh\b',
    r'chmod\s+4777',
    r'rm\s+-rf\s+\*',            # rm -rf * — too destructive
    r'/bin/busybox',             # busybox chaining
]


# ─── Reader + setup derivation ────────────────────────────────────────────────

def derive_pair(cmd: str) -> tuple[str | None, str | None, str | None]:
    """
    Returns (setup, reader, expected_nonempty_hint) or (None, None, None).

    setup  = command to run before creator to establish prerequisites (or None)
    reader = command to verify state after creator
    """
    cmd = cmd.strip()

    # ── FI 1: echo > file ─────────────────────────────────────────────────
    m = re.match(r"echo\s+.+\s+>\s+(\S+)$", cmd)
    if m:
        return None, f"cat {m.group(1)}", None

    # ── FI 1: echo >> file ────────────────────────────────────────────────
    m = re.match(r"echo\s+.+\s+>>\s+(\S+)$", cmd)
    if m:
        path = m.group(1)
        return f"touch {path}", f"cat {path}", None

    # ── FI 1: touch file ──────────────────────────────────────────────────
    m = re.match(r"touch\s+(\S+)$", cmd)
    if m:
        return None, f"ls {m.group(1)}", None

    # ── FI 1: mkdir ───────────────────────────────────────────────────────
    m = re.match(r"mkdir\s+(?:-p\s+)?(\S+)$", cmd)
    if m:
        return None, f"ls -d {m.group(1)}", None

    # ── FI 1: wget/curl download (no pipe) ───────────────────────────────
    # Only safe if not piped to shell — already filtered by SKIP_PATTERNS
    m = re.search(r"wget\s+(?:-\S+\s+)*(\S+://\S+)", cmd)
    if m and "|" not in cmd:
        url = m.group(1)
        # check for -O flag
        o_m = re.search(r"-O\s+(\S+)", cmd)
        fname = o_m.group(1) if o_m else url.rstrip("/").split("/")[-1] or "index.html"
        return None, f"ls {fname}", None

    m = re.search(r"curl\s+.*?-o\s+(\S+)", cmd)
    if m and "|" not in cmd:
        return None, f"ls {m.group(1)}", None

    # ── FI 2: mv src dst ─────────────────────────────────────────────────
    m = re.match(r"mv\s+(\S+)\s+(\S+)$", cmd)
    if m:
        src, dst = m.group(1), m.group(2)
        setup = f"touch {src}"
        return setup, f"ls {dst}", None

    # ── FI 2: cp src dst ─────────────────────────────────────────────────
    m = re.match(r"cp\s+(?:-r\s+)?(\S+)\s+(\S+)$", cmd)
    if m:
        src, dst = m.group(1), m.group(2)
        setup = f"touch {src}"
        return setup, f"ls {dst}", None

    # ── FI 2: chmod +x on file ────────────────────────────────────────────
    m = re.match(r"chmod\s+\+x\s+(\S+)$", cmd)
    if m:
        target = m.group(1)
        if not target.startswith(("/etc", "/bin", "/usr", "/sbin")):
            setup = f"touch {target}"
            return setup, f"ls -la {target} | awk '{{print $1}}'", None

    # ── FI 2: chmod on file ───────────────────────────────────────────────
    m = re.match(r"chmod\s+(\S+)\s+(\S+)$", cmd)
    if m:
        perm, target = m.group(1), m.group(2)
        # skip system paths
        if target.startswith("/etc") or target.startswith("/bin"):
            return None, None, None
        # always touch the file first regardless of path (relative or absolute)
        # so the file exists before chmod runs
        setup = f"touch {target}"
        return setup, f"ls -la {target} | awk '{{print $1}}'", None

    # ── FI 2: sed -i ─────────────────────────────────────────────────────
    m = re.match(r"sed\s+-i\s+'s/(.+?)/(.+?)/g?'\s+(\S+)$", cmd)
    if m:
        old, new, path = m.group(1), m.group(2), m.group(3)
        setup = f"echo '{old}' > {path}"
        return setup, f"cat {path}", None

    # ── FI 2: export VAR=val ─────────────────────────────────────────────
    m = re.match(r"export\s+([A-Za-z_][A-Za-z0-9_]*)=(.+)$", cmd)
    if m:
        var, val = m.group(1), m.group(2).strip("'\"")
        # only simple scalar values
        if re.match(r'^[\w./:-]+$', val):
            return None, f"echo ${m.group(1)}", None

    # ── FI 2: cd dir ─────────────────────────────────────────────────────
    m = re.match(r"cd\s+(\S+)$", cmd)
    if m:
        d = m.group(1)
        if not d.startswith("/etc") and not d.startswith("/bin"):
            setup = f"mkdir -p {d}"
            return setup, f"ls -d {d}", None

    # ── FI 3: crontab -e / crontab install ───────────────────────────────
    if re.match(r"crontab\s+-l", cmd):
        # crontab -l reads — not a state creator, skip
        return None, None, None

    # ── FI 3: systemctl (start/stop/enable) ──────────────────────────────
    m = re.match(r"systemctl\s+(start|stop|enable|disable|restart)\s+(\S+)", cmd)
    if m:
        action, svc = m.group(1), m.group(2)
        return None, f"systemctl is-enabled {svc} 2>/dev/null || echo 'not-found'", None

    # ── FI 4: chmod 777 on a specific file ───────────────────────────────
    m = re.match(r"chmod\s+777\s+(\S+)$", cmd)
    if m:
        target = m.group(1)
        # skip system paths only
        if not target.startswith(("/etc", "/bin", "/usr", "/sbin")):
            setup = f"touch {target}"
            return setup, f"ls -la {target} | awk '{{print $1}}'", None

    # ── FI 4: rm -rf file (specific file, not wildcard) ──────────────────
    m = re.match(r"rm\s+-rf?\s+(\S+)$", cmd)
    if m:
        target = m.group(1)
        # only safe targets — /tmp or relative paths, no wildcards
        if ("*" not in target and "?" not in target and
                (target.startswith("/tmp") or "/" not in target)):
            setup = f"touch {target}"
            return setup, f"ls {target} 2>&1", None

    # ── FI 4: useradd ────────────────────────────────────────────────────
    m = re.match(r"useradd\s+(?:\S+\s+)*(\S+)$", cmd)
    if m:
        return None, f"id {m.group(1)} | grep -o 'uid=[0-9]*'", None

    # ── FI 4: userdel ────────────────────────────────────────────────────
    m = re.match(r"userdel\s+(?:-r\s+)?(\S+)$", cmd)
    if m:
        user = m.group(1)
        setup = f"useradd {user}"
        return setup, f"id {user} 2>&1", None

    # ── chained: cmd1 && cmd2 — try each part ────────────────────────────
    if "&&" in cmd:
        parts = [p.strip() for p in cmd.split("&&")]
        # try last part first, then first part
        for part in reversed(parts):
            s, r, h = derive_pair(part)
            if r:
                return s, r, h

    return None, None, None


# ─── Safety filter ────────────────────────────────────────────────────────────

def is_safe(cmd: str) -> bool:
    base = cmd.strip().split()[0].lstrip("./") if cmd.strip() else ""
    if base in SKIP_BASES:
        return False
    for pat in SKIP_PATTERNS:
        if re.search(pat, cmd):
            return False
    if not cmd.isprintable():
        return False
    # skip commands referencing non-existent network resources
    if re.search(r'ftpget|tftp\b', cmd):
        return False
    return True


# ─── Dataset collection ───────────────────────────────────────────────────────

def collect_commands(max_ml4net=5000):
    cmds = []
    try:
        sessions = load_cyberlab_sessions()
        for s in sessions:
            for c in s.get("commands", []):
                if c.strip():
                    cmds.append((c.strip(), "cyberlab"))
        print(f"[dataset] cyberlab: {sum(1 for _,s in cmds if s=='cyberlab')} commands")
    except Exception as e:
        print(f"[dataset] cyberlab failed: {e}")

    try:
        ml = load_ml4net(max_sessions=max_ml4net)
        for c in ml:
            if c.strip():
                cmds.append((c.strip(), "ml4net"))
        print(f"[dataset] ml4net: {sum(1 for _,s in cmds if s=='ml4net')} commands")
    except Exception as e:
        print(f"[dataset] ml4net failed: {e}")

    return cmds


# ─── Build candidates ─────────────────────────────────────────────────────────

def build_candidates(max_per_fi=25):
    scorer = FIScorer()
    raw    = collect_commands()

    seen, unique = set(), []
    for cmd, src in raw:
        if cmd not in seen:
            seen.add(cmd)
            unique.append((cmd, src))
    print(f"[filter] {len(unique)} unique commands")

    buckets = {1: [], 2: [], 3: [], 4: []}
    skipped_no_reader = {1: 0, 2: 0, 3: 0, 4: 0}

    for cmd, src in unique:
        fi, _ = scorer.score(cmd)
        if fi < 1:
            continue
        if not is_safe(cmd):
            continue
        setup, reader, _ = derive_pair(cmd)
        if reader is None:
            skipped_no_reader[fi] = skipped_no_reader.get(fi, 0) + 1
            continue
        if fi in buckets and len(buckets[fi]) < max_per_fi:
            buckets[fi].append((fi, FI_CATEGORY[fi], cmd, setup, reader, src))

    for fi in [1, 2, 3, 4]:
        print(f"[filter] FI {fi}: {len(buckets[fi])} candidates "
              f"({skipped_no_reader[fi]} dropped — no reader derivable)")

    candidates = []
    for fi in [1, 2, 3, 4]:
        candidates.extend(buckets[fi])
    return candidates


# ─── Docker helpers ───────────────────────────────────────────────────────────

def _run(cmd, check=True):
    # stdin from /dev/null, not inherited. With DOCKER="sudo docker" and an
    # expired sudo timestamp, an inherited tty let sudo print
    # "[sudo] password for ...:" and block the whole collection until someone
    # typed it -- a 50k-command run spent hours asleep at that prompt rather
    # than working. Denied stdin, sudo fails immediately and the error is
    # visible instead of silent.
    return subprocess.run(cmd, shell=True, check=check,
                          stdin=subprocess.DEVNULL,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)


def container_exists():
    r = _run(f"{DOCKER} ps -aq -f name={CONTAINER}", check=False)
    return bool(r.stdout.strip())


def _image_exists():
    r = _run(f"{DOCKER} image inspect {GT_IMAGE}", check=False)
    return r.returncode == 0


def _image_is_stale():
    """True if config.yaml now renders a different Dockerfile than the one the
    existing image was built from.

    Without this, editing config.yaml did nothing: start_container() built
    only when the image was MISSING, so the image kept whatever base, users
    and WORKDIR it was first built with while the regenerated Dockerfile sat
    on disk unused. Two whole collection runs were spent on an image that
    still started every session in / after config said /root, and the only
    cure was knowing to `docker rmi` by hand."""
    try:
        with open(GT_DOCKERFILE, encoding="utf-8") as fh:
            return fh.read() != render_dockerfile()
    except OSError:
        return True            # never built here, or the record is gone


def _build_gt_image():
    """Builds hydrapot-ground-truth once from Dockerfile.ground_truth — bakes
    in config.yaml's system_state.base_tools as real installed packages, the
    declared users, and the starting_files, so ground truth actually matches
    what the honeypot claims to be instead of a bare ubuntu:22.04. No
    per-session/per-reset apt-get needed anymore (that was the real bug:
    reset_container() never reinstalled anything, and even the first
    install silently swallowed errors via 2>/dev/null) — everything's
    already in the image."""
    with open(GT_DOCKERFILE, "w", encoding="utf-8") as fh:
        fh.write(render_dockerfile())
    print(f"[docker] generated {os.path.basename(GT_DOCKERFILE)} from config.yaml "
          f"(ubuntu:{_ubuntu_tag()}, hostname={GT_HOSTNAME})")
    print(f"[docker] building {GT_IMAGE} from {GT_DOCKERFILE} (one-time, ~1-2 min) ...")
    r = _run(f"{DOCKER} build -t {GT_IMAGE} -f {GT_DOCKERFILE} {_HERE}", check=False)
    if r.returncode != 0:
        raise RuntimeError(f"docker build failed:\n{r.stderr}")
    print("[docker] image built")


def _wait_ready(attempts=200):
    """Block until the container accepts an exec, instead of sleeping a fixed
    guess. The old fixed `sleep 0.3` + `sleep 0.5` per reset was both slower
    and less safe than asking: 0.8s x ~3100 sessions is ~41 minutes of pure
    sleeping on a 50k-command collection, while a loaded host can still need
    longer than 0.8s, in which case the first command of the session used to
    fail against a container that was not up yet."""
    for _ in range(attempts):
        if _run(f"{DOCKER} exec {CONTAINER} true", check=False).returncode == 0:
            return
        time.sleep(0.05)
    raise RuntimeError(f"container {CONTAINER} did not become ready")


def start_container():
    if not _image_exists():
        _build_gt_image()
    elif _image_is_stale():
        print("[docker] config.yaml changed since this image was built "
              "— rebuilding")
        _run(f"{DOCKER} rmi -f {GT_IMAGE}", check=False)
        _build_gt_image()
    print(f"[docker] starting {GT_IMAGE} as {CONTAINER} (hostname={GT_HOSTNAME}) ...")
    if container_exists():
        _run(f"{DOCKER} rm -f {CONTAINER}", check=False)
    _run(f"{DOCKER} run -d --name {CONTAINER} --hostname {GT_HOSTNAME} --rm=false "
         f"{GT_IMAGE} sleep infinity")
    _wait_ready()
    print("[docker] ready")


def reset_container():
    _run(f"{DOCKER} rm -f {CONTAINER}", check=False)
    _run(f"{DOCKER} run -d --name {CONTAINER} --hostname {GT_HOSTNAME} --rm=false "
         f"{GT_IMAGE} sleep infinity")
    _wait_ready()


def exec_cmd(cmd, timeout=None):
    """Returns (output, returncode). `timeout` overrides the module default
    for this one command -- a fullscreen program (top, htop, watch, less)
    never exits on its own and burns the full timeout every time, so a
    caller that knows it is running one can ask for a shorter wait. The
    screen such a program paints is identical after 2s and after 10s.

    Captures raw bytes and decodes with
    errors='replace' instead of subprocess's default strict utf-8 — real
    command output sometimes contains a byte that isn't valid utf-8 (binary
    data, unusual locale output, etc.), which would otherwise raise
    UnicodeDecodeError and crash a long-running collection script over a
    single command.

    stderr is merged in via `2>&1` inside the executed command itself (not
    concatenated after the fact, which would lose real interleaving order)
    — a real attacker watching a terminal sees both streams merged, and
    messages like "command not found" go to stderr, so capturing stdout
    alone was silently recording those cases as empty output.

    `-t` allocates a real PTY for the executed command, matching a real
    attacker's interactive SSH session — without it, TTY-dependent tools
    (top, less, clear, etc.) print artifacts like "TERM environment
    variable not set" that a real interactive shell would never show. No
    `-i` — nothing feeds the process input, so a fullscreen program just
    hits the existing TIMEOUT and gets killed, same as today. A PTY also
    makes the kernel translate every '\\n' to '\\r\\n' on output (terminal
    line-ending convention) — stripped back out below, since Cowrie/
    on_device/cloud all generate plain '\\n' and leaving the '\\r' in would
    regress exact-match on every multi-line ground truth for a purely
    cosmetic byte difference, not a real content difference."""
    import shlex
    wrapped = f"({cmd}) 2>&1"
    r = subprocess.run(
        f"{DOCKER} exec -t {CONTAINER} bash -c {shlex.quote(wrapped)}",
        shell=True, capture_output=True, stdin=subprocess.DEVNULL,
        timeout=TIMEOUT if timeout is None else timeout,
    )
    output = r.stdout.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")
    return output.strip(), r.returncode


def stop_container():
    _run(f"{DOCKER} rm -f {CONTAINER}", check=False)
    print("[docker] container removed")


