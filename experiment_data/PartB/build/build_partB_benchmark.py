def build_benchmark(max_per_fi=25, dry_run=False):
    candidates = build_candidates(max_per_fi=max_per_fi)
    print(f"\n[benchmark] {len(candidates)} total pairs")

    if dry_run:
        for fi, cat, creator, setup, reader, src in candidates:
            print(f"  FI={fi} [{src}]")
            if setup:
                print(f"    S: {setup}")
            print(f"    C: {creator}")
            print(f"    R: {reader}")
        return

    start_container()
    records = []

    try:
        for i, (fi, cat, creator, setup, reader, src) in enumerate(candidates, 1):
            pair_id = f"sb_{i:03d}"

            # always reset between pairs for clean state
            if i > 1:
                reset_container()

            print(f"[{pair_id}] FI={fi} [{src}] {creator[:70]}")

            # run setup if needed (establish prerequisites)
            if setup:
                _, s_rc = exec_cmd(setup)
                if s_rc != 0:
                    print(f"  setup FAILED — skip")
                    records.append({
                        "id": pair_id, "category": cat, "fi": fi, "source": src,
                        "setup": setup, "creator": creator, "reader": reader,
                        "ground_truth": "", "ok": False,
                    })
                    continue

            # run creator
            _, c_rc = exec_cmd(creator)

            # run reader → ground truth
            ground_truth, r_rc = exec_cmd(reader)
            print(f"  R: {reader}")
            print(f"  gt: {repr(ground_truth[:80])}")

            ok = (r_rc == 0 and ground_truth.strip() != "")
            records.append({
                "id":           pair_id,
                "category":     cat,
                "fi":           fi,
                "source":       src,
                "setup":        setup,
                "creator":      creator,
                "reader":       reader,
                "ground_truth": ground_truth,
                "ok":           ok,
            })

    finally:
        stop_container()

    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(records, f, indent=2, ensure_ascii=False)

    ok_count = sum(1 for r in records if r["ok"])
    print(f"\n[done] {ok_count}/{len(records)} valid pairs → {OUTPUT_PATH}")

    from collections import Counter
    print("\nFI breakdown:")
    for fi in [1, 2, 3, 4]:
        subset = [r for r in records if r["fi"] == fi]
        ok_n   = sum(1 for r in subset if r["ok"])
        print(f"  FI {fi} ({FI_CATEGORY[fi]}): {ok_n}/{len(subset)} valid")

    print("\nSource breakdown:")
    for src, n in sorted(Counter(r["source"] for r in records).items()):
        print(f"  {src}: {n}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max-per-fi", type=int, default=25,
                    help="Max pairs per FI band (default 25 → ~100 total)")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    build_benchmark(max_per_fi=args.max_per_fi, dry_run=args.dry_run)


if __name__ == "__main__":
    main()