def _ubuntu_tag() -> str:
    """`Ubuntu 22.04 LTS` -> `22.04`. The declared OS picks the base image, so
    bumping honeypot.os rebuilds against the matching Ubuntu."""
    m = re.search(r"(\d+\.\d+)", _CFG.honeypot.os or "")
    if not m:
        raise RuntimeError(f"cannot derive a base image from honeypot.os="
                           f"{_CFG.honeypot.os!r}")
    return m.group(1)


def _size_bytes(size: str) -> int:
    """`3.7K` -> 3789, `161B` -> 161. starting_files declares sizes this way."""
    m = re.match(r"^([\d.]+)\s*([BKMG]?)$", (size or "0B").strip(), re.I)
    if not m:
        return 0
    n, unit = float(m.group(1)), (m.group(2) or "B").upper()
    return int(n * {"B": 1, "K": 1024, "M": 1024 ** 2, "G": 1024 ** 3}[unit])


def render_dockerfile() -> str:
    """The ground-truth Dockerfile, generated from config.yaml."""
    ss = _CFG.system_state or {}
    users = ss.get("users") or {}
    files = ss.get("starting_files") or {}
    L = [
        "# GENERATED by build_partB_benchmark.render_dockerfile() —"
        " DO NOT EDIT.",
        "# Every value is derived from config.yaml so the reference box cannot"
        " drift",
        "# from the honeypot it is the reference for. Edit config.yaml instead.",
        "#",
        "# Known, deliberately-unaddressed gap: the kernel. Containers share the"
        " host",
        f"# kernel, while config declares {_CFG.honeypot.kernel} — matching it"
        " would need",
        "# fragile uname() spoofing, so ground truth reports the host's.",
        f"FROM ubuntu:{_ubuntu_tag()}",
        "ENV DEBIAN_FRONTEND=noninteractive",
        "",
        "RUN apt-get update -qq && apt-get install -y --no-install-recommends \\",
        "    " + " ".join(_GT["packages"]) + " \\",
        "    && rm -rf /var/lib/apt/lists/*",
        "",
        "# Best effort: a renamed or dropped package must not fail the build.",
        "RUN apt-get update -qq && ( apt-get install -y --no-install-recommends \\",
        "    " + " ".join(_GT["best_effort_packages"]) + " \\",
        "    || true ) && rm -rf /var/lib/apt/lists/*",
        "",
        "# Accounts from system_state.users. Guarded by `id -u`: the system ones",
        "# already exist via base-passwd, and useradd would fail the build.",
    ]
    for name, u in sorted(users.items(), key=lambda kv: kv[1].get("uid", 0)):
        if name == "root":
            continue                       # always present
        uid = u.get("uid")
        home = u.get("home") or f"/home/{name}"
        shell = u.get("shell") or "/usr/sbin/nologin"
        gecos = (u.get("gecos") or "").replace('"', "")
        opts = [f"-u {uid}" if uid is not None else "",
                f"-d {home}", f"-s {shell}",
                f'-c "{gecos}"' if gecos else "",
                "-m" if str(home).startswith("/home") else ""]
        L.append(f"RUN id -u {name} >/dev/null 2>&1 || "
                 f"useradd {' '.join(o for o in opts if o)} {name}")
    L += ["", "# Files from system_state.starting_files — declared perms and size.",
          "# Content was never specified, only perms/size, so filler is padded",
          "# to the declared length."]
    for path, meta in files.items():
        perms = meta.get("perms", "-rw-r--r--")
        if perms.startswith("d"):
            L.append(f"RUN mkdir -p {path} && chmod {_octal(perms)} {path}")
            continue
        n = _size_bytes(meta.get("size"))
        parent = posixpath.dirname(path) or "/"
        gen = (f"head -c {n} /dev/zero | tr '\\0' '#'" if n else "printf ''")
        L.append(f"RUN mkdir -p {parent} && {gen} > {path} && "
                 f"chmod {_octal(perms)} {path}")
    L += ["", 'CMD ["sleep", "infinity"]', ""]
    return "\n".join(L)


def _octal(perms: str) -> str:
    """`-rw-r--r--` -> `644`. chmod takes the octal, config states the string."""
    bits = perms[1:10].ljust(9, "-")
    out = ""
    for i in range(0, 9, 3):
        trio = bits[i:i + 3]
        out += str((4 if trio[0] == "r" else 0) +
                   (2 if trio[1] == "w" else 0) +
                   (1 if trio[2] in "xs" else 0))
    return out

