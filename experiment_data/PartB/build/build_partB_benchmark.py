"""
experiment_data/PartB/build_partB_benchmark.py
─────────────────────────────────────────────────────────────────
Generates the Part B stateful benchmark from REAL attacker commands
sourced from cyberlab + ML4Net datasets, filtered by FI score.

Core idea (Prof's suggestion):
  FI 0 = stateless (read/display) — excluded
  FI 1-4 = stateful (creates/modifies/impacts state) — included

For each stateful creator command:
  - FI 1-2: derive reader directly from command
  - FI 3-4: use a setup step to create prerequisite state first,
            then run the creator, then verify

Output:
  dataset/partB_stateful_benchmark.json (relative to repo root)

Each record:
{
  "id":           "sb_001",
  "category":     "fi_1_create",
  "fi":           1,
  "source":       "cyberlab" | "ml4net" | "handcrafted",
  "setup":        "<setup command or null>",
  "creator":      "<real attacker command>",
  "reader":       "<verification command>",
  "ground_truth": "<docker output>",
  "ok":           true
}

Usage:
  python experiment_data/PartB/build_partB_benchmark.py --dry-run
  python experiment_data/PartB/build_partB_benchmark.py --max-per-fi 25
"""

